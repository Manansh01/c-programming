#include <stdio.h>

int main() {
    int age = 25;
    float height = 5.9f;
    double pi = 3.141592653589793;
    char grade = 'A';

    printf("age = %d\n", age);
    printf("height = %.1f\n", height);
    printf("pi = %.15f\n", pi);
    printf("grade = %c\n", grade);

    int x = 10, y = 20;
    int sum = x + y;
    printf("sum = %d\n", sum);

    return 0;
}
