#include <stdio.h>

int main(void)
{
    printf("New line: Hello \nWorld \n");
    printf("Tab: A \tB\tC \n");
    printf("Backslash: \\ \n");
    printf("Quote: \"Hello\" \n");
    printf("Single quote: \'A\' \n");
    printf("Alert: \a \n");
    printf("Backspace: A\b B \n");
    printf("Carriage return: Hello\r World\n");
    printf("Form feed: A \fB \n");
    printf("Vertical tab: A\vB \n");
    printf("Question mark: ? \n");

    return 0;
}
